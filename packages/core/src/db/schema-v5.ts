/**
 * Schema v5 — multi-PC foundation (v1.1.4).
 *
 * STRICTLY ADDITIVE. No existing table or column is touched; every statement is
 * `CREATE ... IF NOT EXISTS`. A v1.1.3 database upgraded with this migration keeps
 * every product, sale, journal line and user exactly as it was, and `migrate()`
 * still writes a pre-migration file copy before running it.
 *
 * Conventions follow the rest of the schema:
 *  - technical timestamps are UTC ISO strings ("2026-11-04T10:00:00.000Z");
 *  - business documents keep local wall-clock text;
 *  - money stays in integer poisa (nothing here stores money at all);
 *  - rows that represent access are revocable, never deleted.
 */

export const SCHEMA_V5 = /* sql */ `
/* ---------- store / server identity ---------------------------------- */
/* Exactly one row. store_id is what every device licence is bound to.  */
CREATE TABLE IF NOT EXISTS store_servers (
  id               INTEGER PRIMARY KEY CHECK (id = 1),
  store_id         TEXT NOT NULL UNIQUE,
  server_id        TEXT NOT NULL UNIQUE,
  server_name      TEXT NOT NULL DEFAULT '',
  cert_fingerprint TEXT,
  created_at       TEXT NOT NULL,
  updated_at       TEXT NOT NULL
);

/* ---------- enrolled devices (a "terminal" is a Windows PC) ---------- */
CREATE TABLE IF NOT EXISTS terminals (
  device_id     TEXT PRIMARY KEY,
  device_name   TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('SERVER_POS','CLIENT_POS','CLIENT_MANAGEMENT')),
  store_id      TEXT NOT NULL,
  license_id    TEXT,
  status        TEXT NOT NULL CHECK (status IN ('pending','approved','rejected','revoked')),
  public_key    TEXT,
  platform      TEXT,
  app_version   TEXT,
  fingerprint   TEXT,
  requested_at  TEXT NOT NULL,
  decided_at    TEXT,
  decided_by    INTEGER REFERENCES users(id),
  decision_note TEXT,
  last_seen     TEXT,
  revoked_at    TEXT
);
CREATE INDEX IF NOT EXISTS idx_terminals_status ON terminals(status, requested_at);

/* Device secrets are 32 random bytes generated by the server; only a SHA-256
   digest is stored, so a stolen database cannot be replayed against the API. */
CREATE TABLE IF NOT EXISTS terminal_credentials (
  device_id   TEXT PRIMARY KEY REFERENCES terminals(device_id) ON DELETE CASCADE,
  secret_hash TEXT NOT NULL,
  created_at  TEXT NOT NULL,
  rotated_at  TEXT,
  last_used   TEXT
);

/* Sessions are persisted so a host restart no longer logs every terminal out
   silently, and so an administrator can see and revoke who is connected. */
CREATE TABLE IF NOT EXISTS terminal_sessions (
  id         TEXT PRIMARY KEY,
  device_id  TEXT NOT NULL REFERENCES terminals(device_id) ON DELETE CASCADE,
  user_id    INTEGER NOT NULL REFERENCES users(id),
  issued_at  TEXT NOT NULL,
  last_seen  TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  revoked_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_terminal_sessions_device ON terminal_sessions(device_id, revoked_at);

/* One row per licence that a device presented and the server accepted. */
CREATE TABLE IF NOT EXISTS device_licenses (
  license_id    TEXT PRIMARY KEY,
  store_id      TEXT NOT NULL,
  device_id     TEXT NOT NULL,
  role          TEXT NOT NULL,
  capacity      INTEGER NOT NULL DEFAULT 1,
  edition       TEXT,
  issued_at     TEXT NOT NULL,
  expires_at    TEXT,
  status        TEXT NOT NULL CHECK (status IN ('active','revoked','superseded')),
  payload       TEXT NOT NULL,
  registered_at TEXT NOT NULL,
  revoked_at    TEXT,
  revoke_reason TEXT
);
CREATE INDEX IF NOT EXISTS idx_device_licenses_store ON device_licenses(store_id, status);

/* Short-lived, single-use pairing codes shown as a QR on the Main PC. */
CREATE TABLE IF NOT EXISTS pairing_tokens (
  token_hash TEXT PRIMARY KEY,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  used_at    TEXT,
  used_by    TEXT,
  created_by INTEGER
);

/* Retry protection: a repeated write (same key + same body) returns the stored
   response instead of running the business operation twice. */
CREATE TABLE IF NOT EXISTS idempotency_keys (
  key          TEXT PRIMARY KEY,
  device_id    TEXT,
  method       TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  response     TEXT,
  created_at   TEXT NOT NULL,
  expires_at   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_idempotency_expiry ON idempotency_keys(expires_at);

/* Outbox: written inside the same transaction as the business operation, then
   streamed to terminals. seq is the store-wide ordering used for resume. */
CREATE TABLE IF NOT EXISTS event_outbox (
  seq            INTEGER PRIMARY KEY AUTOINCREMENT,
  event_id       TEXT NOT NULL UNIQUE,
  store_id       TEXT NOT NULL,
  type           TEXT NOT NULL,
  entity_id      TEXT,
  payload        TEXT NOT NULL DEFAULT '{}',
  schema_version INTEGER NOT NULL DEFAULT 1,
  created_at     TEXT NOT NULL,
  delivered_at   TEXT
);
CREATE INDEX IF NOT EXISTS idx_event_outbox_created ON event_outbox(seq);
`;
